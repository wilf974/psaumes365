'use client'

import { useState, useEffect } from 'react'
import Link from 'next/link'
import { usePathname } from 'next/navigation'
import { signOut, useSession } from 'next-auth/react'
import { motion, AnimatePresence } from 'framer-motion'
import { cn } from '@/lib/utils'
import { Button } from '@/components/ui/button'
import { ThemeToggle } from '@/components/theme-toggle'
import { Logo } from '@/components/ui/logo'

interface MainNavProps {
  user: {
    name?: string | null
    email: string
  }
}

/**
 * Navigation principale de l'application
 * Affiche les liens de navigation et le menu utilisateur
 * Responsive avec menu hamburger pour mobile
 */
export function MainNav({ user }: MainNavProps) {
  const pathname = usePathname()
  const [mobileMenuOpen, setMobileMenuOpen] = useState(false)
  const { data: session } = useSession()
  const userRole = (session?.user as any)?.role

  const navItems = [
    { href: '/accueil', label: 'Accueil', icon: HomeIcon },
    { href: '/recherche', label: 'Recherche', icon: SearchIcon },
    { href: '/plans', label: 'Plans', icon: PlansIcon },
    { href: '/journal', label: 'Journal', icon: JournalIcon },
    { href: '/favoris', label: 'Favoris', icon: StarIcon },
    { href: '/statistiques', label: 'Stats', icon: StatsIcon },
    { href: '/parametres', label: 'Paramètres', icon: SettingsIcon },
  ]

  // Ajouter le lien admin si l'utilisateur est admin ou contributeur
  if (userRole === 'ADMIN' || userRole === 'CONTRIBUTOR') {
    navItems.push({ href: '/admin', label: 'Admin', icon: AdminIcon })
  }

  return (
    <>
      <header className="sticky top-0 z-50 w-full border-b border-border/40 bg-background/95 backdrop-blur supports-[backdrop-filter]:bg-background/60">
        <div className="container flex h-14 sm:h-16 items-center justify-between px-3 sm:px-4 max-w-6xl mx-auto">
        {/* Logo */}
        <Link href="/accueil" className="flex items-center max-w-[120px] sm:max-w-none">
          <Logo size={32} className="sm:w-auto" />
        </Link>

        {/* Navigation Desktop */}
        <nav className="hidden md:flex items-center gap-1">
          {navItems.map((item) => {
            const isActive = pathname === item.href
            return (
              <Link key={item.href} href={item.href}>
                <motion.div
                  className={cn(
                    'flex items-center gap-2 px-3 py-2 rounded-xl text-sm font-medium transition-colors',
                    isActive
                      ? 'bg-primary/10 text-primary'
                      : 'text-muted-foreground hover:text-foreground hover:bg-muted'
                  )}
                  whileHover={{ scale: 1.02 }}
                  whileTap={{ scale: 0.98 }}
                >
                  <item.icon className="w-4 h-4" />
                  <span>{item.label}</span>
                </motion.div>
              </Link>
            )
          })}
        </nav>

        {/* Menu utilisateur Desktop */}
        <div className="hidden md:flex items-center gap-2">
          <ThemeToggle />
          <span className="text-sm text-muted-foreground">
            {user.name || user.email.split('@')[0]}
          </span>
          <Button
            variant="ghost"
            size="sm"
            onClick={() => signOut({ callbackUrl: '/' })}
            className="text-muted-foreground"
          >
            <LogoutIcon className="w-4 h-4" />
          </Button>
        </div>

        {/* Menu Mobile - Bouton hamburger */}
        <div className="flex md:hidden items-center gap-2">
          <ThemeToggle />
          <Button
            variant="ghost"
            size="sm"
            onClick={(e) => {
              e.preventDefault()
              e.stopPropagation()
              const newState = !mobileMenuOpen
              console.log('Menu toggle:', newState)
              setMobileMenuOpen(newState)
            }}
            className="text-muted-foreground"
            aria-label="Menu"
            aria-expanded={mobileMenuOpen}
          >
            {mobileMenuOpen ? (
              <CloseIcon className="w-5 h-5" />
            ) : (
              <MenuIcon className="w-5 h-5" />
            )}
          </Button>
        </div>
      </div>
    </header>

    {/* Menu Mobile - Overlay et Menu */}
      {mobileMenuOpen && (
        <div className="md:hidden">
          {/* Overlay */}
          <div
            className="fixed inset-0 bg-black/60 z-[9998]"
            onClick={() => setMobileMenuOpen(false)}
            style={{ 
              position: 'fixed',
              top: 0,
              left: 0,
              right: 0,
              bottom: 0,
              zIndex: 9998
            }}
          />
          {/* Menu Panel */}
          <motion.div
            initial={{ x: '100%' }}
            animate={{ x: 0 }}
            exit={{ x: '100%' }}
            transition={{ type: 'spring', damping: 25, stiffness: 200 }}
            className="fixed top-14 sm:top-16 right-0 bottom-0 w-[85vw] max-w-xs bg-white dark:bg-[#1e1e1e] border-l border-gray-200 dark:border-gray-800 shadow-2xl z-[9999] overflow-y-auto"
            onClick={(e) => e.stopPropagation()}
            style={{ 
              position: 'fixed',
              top: '3.5rem',
              right: 0,
              bottom: 0,
              width: '85vw',
              maxWidth: '20rem',
              zIndex: 9999,
              backgroundColor: 'hsl(var(--card))'
            }}
          >
              <div className="p-4 space-y-2">
                {/* Info utilisateur */}
                <div className="px-3 py-2 mb-4 border-b border-border">
                  <p className="text-sm font-medium text-foreground">
                    {user.name || user.email.split('@')[0]}
                  </p>
                  <p className="text-xs text-muted-foreground">{user.email}</p>
                </div>

                {/* Navigation mobile */}
                {navItems.map((item) => {
                  const isActive = pathname === item.href
                  return (
                    <Link
                      key={item.href}
                      href={item.href}
                      onClick={() => setMobileMenuOpen(false)}
                    >
                      <motion.div
                        className={cn(
                          'flex items-center gap-3 px-4 py-3 rounded-xl text-sm font-medium transition-colors',
                          isActive
                            ? 'bg-primary/10 text-primary'
                            : 'text-muted-foreground hover:text-foreground hover:bg-muted'
                        )}
                        whileTap={{ scale: 0.98 }}
                      >
                        <item.icon className="w-5 h-5" />
                        <span>{item.label}</span>
                      </motion.div>
                    </Link>
                  )
                })}

                {/* Déconnexion */}
                <div className="pt-4 mt-4 border-t border-border">
                  <Button
                    variant="ghost"
                    size="sm"
                    onClick={() => signOut({ callbackUrl: '/' })}
                    className="w-full justify-start text-muted-foreground"
                  >
                    <LogoutIcon className="w-4 h-4 mr-3" />
                    Déconnexion
                  </Button>
                </div>
              </div>
          </motion.div>
        </div>
      )}
    </>
  )
}

